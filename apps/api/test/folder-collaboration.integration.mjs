// Run after building: node --env-file=.env test/folder-collaboration.integration.mjs
// Creates isolated test users and deletes only their data in finally.
import assert from "node:assert/strict"
import { randomUUID } from "node:crypto"
import { createRequire } from "node:module"
const require = createRequire(import.meta.url)
const { PrismaClient } = require("@prisma/client")
const { PrismaPg } = require("@prisma/adapter-pg")
const { FoldersService } = require("../dist/modules/cabinet/folders/folders.service.js")
const { BookmarksService } = require("../dist/modules/cabinet/bookmarks/bookmarks.service.js")

if (!process.env.DATABASE_URL || process.env.NODE_ENV === "production") throw new Error("Use a development database only")
const prisma = new PrismaClient({ adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL }) })
const users = [randomUUID(), randomUUID(), randomUUID()]
const [owner, member, outsider] = users
const folders = new FoldersService(prisma)
const bookmarks = new BookmarksService(prisma, { extract: async () => ({}) }, { isVideoUrl: () => false }, { enqueue: async () => true }, {})
try {
  await prisma.user.createMany({ data: users.map((id) => ({ id, email: `collaboration-${id}@example.com`, name: "Collaboration check" })) })
  const parent = await folders.create(owner, { name: "Private parent" })
  const folder = await folders.create(owner, { name: "Shared", parentId: parent.id })
  const child = await folders.create(owner, { name: "Private child", parentId: folder.id })
  const original = await bookmarks.create(owner, { title: "Owner link", url: "https://example.com/owner", folderId: folder.id })
  await bookmarks.create(owner, { title: 'Private child reference', url: 'https://example.com/child', folderId: child.id })
  assert.equal((await bookmarks.findAll(member, { search: 'Owner link' })).totalCount, 0)
  await bookmarks.saveNote(owner, randomUUID(), { title: "Private note", noteDocument: { type: "doc", content: [] }, folderId: folder.id })
  await prisma.bookmark.update({ where: { id: original.id }, data: { notes: "secret-search-marker" } })

  const invitation = await folders.enableInvite(owner, folder.id)
  assert.notEqual((await prisma.folder.findUnique({ where: { id: folder.id } })).inviteTokenHash, invitation.token)
  assert.deepEqual(await folders.acceptInvite(member, invitation.token), { folderId: folder.id })
  await folders.acceptInvite(member, invitation.token)
  assert.equal(await prisma.folderMember.count({ where: { folderId: folder.id } }), 1)
  const visibleFolders = await folders.findAll(member)
  assert.deepEqual(visibleFolders.map((item) => item.id), [folder.id])
  assert.equal(visibleFolders[0].parentId, null)
  assert.equal(visibleFolders[0].inviteTokenHash, undefined)
  assert.equal(visibleFolders[0].shareToken, undefined)
  await assert.rejects(() => bookmarks.findAll(member, { folderId: parent.id }), /Folder not found/)
  await assert.rejects(() => bookmarks.findAll(member, { folderId: child.id }), /Folder not found/)
  await assert.rejects(() => bookmarks.findAll(outsider, { folderId: folder.id }), /Folder not found/)

  const contributed = await bookmarks.create(member, { title: "Member link", url: "https://example.com/member", folderId: folder.id })
  const collection = await bookmarks.findAll(member, { folderId: folder.id })
  assert.equal(collection.totalCount, 2)
  assert.equal(collection.data.find((item) => item.id === original.id).canEdit, false)
  assert.equal(collection.data.find((item) => item.id === original.id).notes, null)
  assert.equal(collection.data.find((item) => item.id === contributed.id).canEdit, true)
  assert.equal((await bookmarks.findAll(member, { folderId: folder.id, search: "secret-search-marker" })).totalCount, 0)
  assert.equal((await bookmarks.findAll(owner, { folderId: folder.id })).totalCount, 3)
  const global = await bookmarks.findAll(member, { search: 'Owner link', limit: 20 })
  assert.deepEqual(global.data.map((item) => item.id), [original.id])
  assert.equal(global.data[0].notes, null)
  assert.equal((await bookmarks.findAll(member, { search: 'secret-search-marker' })).totalCount, 0)
  assert.equal((await bookmarks.findAll(member, { search: 'Private note' })).totalCount, 0)
  assert.equal((await bookmarks.findAll(member, { search: 'Private child reference' })).totalCount, 0)
  assert.equal((await bookmarks.findAll(outsider, { search: 'Owner link' })).totalCount, 0)
  await bookmarks.update(member, contributed.id, { notes: 'Persist inspector draft' })
  assert.equal((await bookmarks.findAll(member, { search: 'Persist inspector draft' })).data[0].notes, 'Persist inspector draft')
  await bookmarks.update(member, contributed.id, { notes: '', description: '', folderId: null })
  assert.equal((await bookmarks.findOne(member, contributed.id)).folderId, null)
  assert.equal((await bookmarks.findOne(member, contributed.id)).notes, '')
  await bookmarks.update(member, contributed.id, { folderId: folder.id })
  await assert.rejects(() => bookmarks.update(member, original.id, { title: "overwrite" }), /Bookmark not found/)
  await assert.rejects(() => bookmarks.remove(member, original.id), /Bookmark not found/)
  await assert.rejects(() => bookmarks.remove(owner, contributed.id), /Bookmark not found/)
  assert.equal((await bookmarks.bulkTrash(member, [original.id])).trashed, 0)
  assert.equal((await bookmarks.update(member, contributed.id, { title: "Edited" })).title, "Edited")
  await assert.rejects(() => folders.update(member, folder.id, { name: "overwrite" }), /Folder not found/)
  await assert.rejects(() => folders.enableInvite(member, folder.id), /Folder not found/)
  await assert.rejects(() => folders.remove(member, folder.id), /Folder not found/)

  await folders.disableInvite(owner, folder.id)
  assert.equal((await bookmarks.findAll(member, { folderId: folder.id })).totalCount, 2)
  await assert.rejects(() => folders.acceptInvite(outsider, invitation.token), /Invitation not found/)
  const second = await folders.enableInvite(owner, folder.id)
  await folders.removeMember(owner, folder.id, member)
  await assert.rejects(() => bookmarks.findAll(member, { folderId: folder.id }), /Folder not found/)
  assert.equal((await bookmarks.findAll(member, { search: 'Owner link' })).totalCount, 0)
  await assert.rejects(() => folders.acceptInvite(member, second.token), /Invitation not found/)
  await assert.rejects(() => bookmarks.create(member, { title: "Denied", url: "https://example.com/denied", folderId: folder.id }), /Target folder not found/)
  assert.ok(await prisma.bookmark.findUnique({ where: { id: contributed.id } }))
  console.log("PASS multi-account collaboration: invite, join, contribution, private notes, ownership, global search permissions, inspector notes/clears/root move, revocation, no inherited access")
} finally {
  await prisma.user.deleteMany({ where: { id: { in: users } } })
  await prisma.$disconnect()
}
